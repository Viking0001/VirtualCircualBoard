def char_to_row(char, hspace=1):
    """
    Převede jeden znak na jeden řádek komponent (podle 5x7 Fontu).
    Výsledek je pole o rozměrech (1, šířka).
    """
    if char not in FONT_5x7:
        print(f"Warning: Znak '{char}' není ve fontu. Přeskakuji.")
        return None

    glyph = FONT_5x7[char]  # 7x5 bitů
    
    # 5x7 -> bitový řetězec (podobně jako v původním skriptu)
    # Každý řádek glyphu má 5 bitů. Původní logika: "0" + row (5b) = 6b?
    # Ale v původním kódu bylo bitstring = "0" + row... a pak bitstring = "000000" + bitstring
    # Cílem je zřejmě dostat 41+ bitů (pro 5x7 + padding).
    
    bit_list = []
    for row in glyph:
        bit_list.append(0) # Padding bit z původního kódu
        bit_list.extend(row)
    
    # Obrácení a padding jako v původním kódu
    bitstring = ''.join(str(b) for b in bit_list)[::-1]
    bitstring = "000000" + bitstring # Padding na začátek
    
    top_row = []
    bottom_row = []
    last_row = []
    for b in bitstring:
        # Původní logika: b == "1" je NONE (vypnutý buffer), b == "0" je BUFFER (zapnutý)
        if b == "0":  # BUFFER
            # Horní řádek: CROSS | WRITE | TC_YELLOW_C
            top_row.append(ComponentType.CROSS)       # Vlevo od WRITE
            top_row.append(ComponentType.WRITE)       # Nad BUFFERem
            top_row.append(ComponentType.TC_YELLOW_C) # Vpravo od WRITE

            # Spodní řádek: READ | BUFFER | NONE
            bottom_row.append(ComponentType.READ)
            bottom_row.append(ComponentType.BUFFER)
            bottom_row.append(ComponentType.NONE)
        else:  # NONE
            # Horní řádek: CROSS | WRITE | TC_YELLOW_C (vždy, pro zachování struktury)
            top_row.append(ComponentType.CROSS)
            top_row.append(ComponentType.WRITE)
            top_row.append(ComponentType.TC_YELLOW_C)

            # Spodní řádek: READ | NONE | NONE
            bottom_row.append(ComponentType.READ)
            bottom_row.append(ComponentType.NONE)
            bottom_row.append(ComponentType.NONE)
        
        # Třetí řádek: Vždy NONE (nebo cokoli co uživatel chtěl, ale musí mít stejnou šířku)
        # Uživatel přidal TC_YELLOW_C na začátek v manuálním editu?
        # Aby to nepadalo, musí mít každá trojice sloupců stejnou šířku.
        last_row.extend([ComponentType.TC_YELLOW_C, ComponentType.NONE, ComponentType.NONE])

    # Výsledek jsou 3 řádky nad sebou
    return np.array([top_row, bottom_row, last_row])

if __name__ == "__main__":
    input_file = "latters/latters.txt"
    if not os.path.exists(input_file):
        print(f"Error: {input_file} nebyl nalezen.")
        exit(1)

    with open(input_file, "r") as f:
        lines = [line.strip('\n') for line in f if line.strip('\n')]

    all_letter_rows = []
    
    # Potřebujeme znát šířku pro prázdné řádky. Font má pro všechny znaky stejnou šířku.
    sample_row = char_to_row('A')
    row_width = sample_row.shape[1]

    for line in lines:
        if line.startswith('\\'):
            # Vložení prázdného řádku (pouze NONE)
            blank_row = np.full((3, row_width), ComponentType.NONE, dtype=object)
            all_letter_rows.append(blank_row)
        else:
            char = line[0]
            comp_row = char_to_row(char)
            if comp_row is not None:
                all_letter_rows.append(comp_row)

    if not all_letter_rows:
        print("Nebyla nalezena žádná platná písmena ani prázdné řádky.")
        exit(1)

    # Spojení řádků pod sebe s mezerou 2 kostiček
    final_width = all_letter_rows[0].shape[1]
    gap_row = np.full((0, final_width), ComponentType.NONE, dtype=object)
    
    stacked_components = all_letter_rows[0]
    for i in range(1, len(all_letter_rows)):
        stacked_components = np.vstack([stacked_components, gap_row, all_letter_rows[i]])

    blueprint = create_simple_blueprint(
        stacked_components,
        name="Letter ROM",
        description="Alphabet stacked vertically with 2-block gap",
        tags="logic,font,rom"
    )

    print(blueprint)